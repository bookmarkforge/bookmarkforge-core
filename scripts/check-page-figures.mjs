#!/usr/bin/env node
/**
 * scripts/check-page-figures.mjs
 *
 * CI gate: the figure-bearing claims on the generated public pages must agree
 * with the code — same truth, same evaluator, different surfaces than
 * check-manual-figures. Born from the page-figures probe (2026-09-16): the
 * localized legal pages gained the full pricing skeleton (ADR-049 follow-up)
 * and no gate covered the 30 public/<locale>/privacy-and-terms.html pages
 * (check-claim-drift only scans public/*.html at the root) nor the Pocket
 * landing.
 *
 * Surfaces:
 *   - public/<locale>/privacy-and-terms.html for the 30 supported locales
 *     (EN at the root) — the generator output of generate-privacy-pages.mjs;
 *   - the 30 generated landing pages (landing.html + 29 localized) — both
 *     surfaces ship the SAME locale set, so LANDING_FILES is derived from
 *     LOCALES below and a locale added here covers both; deriving one side
 *     by hand is what left the 24 expansion landings (ar, bg, …, zh) outside
 *     every figures gate while their copy already carried prices;
 *   - public/pocket-alternative.html (generated by build-landings.cjs since
 *     the generator was wired up — see its TODO-resolution commit).
 *
 * Reuse, not duplication: the figure rules live in
 * check-manual-figures.mjs's evaluateManual (pairNumUnits number↔unit
 * coupling, $-anchored price rule, offer-cap rule). This gate adapts the
 * surface: HTML tags are stripped line-wise so line numbers match the raw
 * file, inline JSON-LD is compacted so its \u0026 escapes cannot fabricate
 * numbers, and spoken competitor prices ("28 dollars every year") are
 * neutralized per the documented convention (patch-landing-copy.mjs):
 * competitor amounts are written without "$" — a spoken price near a
 * competitor name is masked; a spoken price with no $ anywhere on the line
 * is never ours, because our own prices are always $-tagged.
 *
 * Fail-closed like the manual gate: truth constants that cannot be parsed
 * abort the run with exit 2.
 */

import { readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { LANDING_CODES as REGISTRY_ALL_CODES } from "./landing-registry.mjs";

const THIS_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(THIS_DIR, "..");

const MANUAL_GATE = await import(
  pathToFileURL(join(THIS_DIR, "check-manual-figures.mjs")).href
);

// The 30 supported locales — registry-derived (EN included), one set for
// the privacy pages AND the landings (LANDING_FILES derives from this).
const LOCALES = REGISTRY_ALL_CODES;

/** Landing pages for the same 30 locales the privacy pages cover: EN is the
 *  root landing.html, every other locale gets public/<code>.html. Kept in
 *  step with check-seo.mjs's LANDING_LANG_CODES (same set, EN included). */
const LANDING_FILES = LOCALES.map((l) => (l === "en" ? "landing.html" : `${l}.html`));
const POCKET_FILE = "pocket-alternative.html";

/** Spoken-price competitor neutralization (see module doc). Our own prices
 * are $-tagged, so on competitor-named lines we mask only SPOKEN PRICES — a
 * number followed by a currency word. Our own one-time price survives the
 * mask when the one-time marker follows ("59 dollars once", "59 dólares una
 * vez", …): the competitor is always the recurring price ("28 dollars every
 * year"), ours is always the lifetime one — that asymmetry is the copy's
 * whole point. Non-price numbers on these lines ("Free: 1,000 bookmarks")
 * stay visible and get validated like any other claim. */
const COMPETITOR_RE = /\braindrop|pocket\b|notion\b|obsidian\b|pinboard\b|raindrop\.io\b/i;
const SPOKEN_PRICE_RE = /(\d+(?:[.,]\d+)*)\s+(dollars?|d[óo]lares?|Dollar|dollari|euro[ns]?)/i;
const ONCE_MARKER_RE = /\b(once|una vez|une (?:seule )?fois|einmal|uma vez|una (?:sola )?volta|una volta)\b/i;
function neutralizeSpokenPrices(line) {
  if (!COMPETITOR_RE.test(line) || line.includes("$")) return line;
  return line.replace(SPOKEN_PRICE_RE, (match, num, currency, offset) => {
    const tail = line.slice(offset + match.length, offset + match.length + 40);
    if (ONCE_MARKER_RE.test(tail)) return match; // ours: keep and validate
    return " ".repeat(num.length) + ` ${currency}`;
  });
}

/** Inline JSON-LD is compacted: its `\u0026`-style escapes can fabricate
 * digit pairs (\u0026 → "&", but older shapes leaked "\u002" + "6") and its
 * long single lines defeat line-level pairing. Compacting collapses the
 * JSON-LD block into ONE synthetic line so any number in it is still
 * checked as a whole. */
function compactJsonLd(lines) {
  let inScript = false;
  const out = [];
  let buf = [];
  for (const line of lines) {
    if (/<script type="application\/ld\+json">/i.test(line)) {
      inScript = true;
      buf = [];
      continue;
    }
    if (inScript && /<\/script>/i.test(line)) {
      out.push(buf.join(" "));
      out.push("</script>");
      inScript = false;
      continue;
    }
    if (inScript) {
      buf.push(line);
      continue;
    }
    out.push(line);
  }
  return out.join("\n");
}

/** Tag-strip per line (keeps 1:1 line numbers for actionable messages).
 * Before stripping, the value of semantic meta tags (description, og:/
 * twitter: description and title) is appended to the line: the JSON-borne
 * copy lives in attributes ("...59 dollars once. Free: 1,000 bookmarks.")
 * and pure tag-stripping made every meta claim invisible to the rules.
 * Viewport/theme-color/image metas stay excluded — their numbers are layout
 * noise (1200×630, initial-scale=1.0), not claims. */
const SEMANTIC_META_RE =
  /<meta\s+[^>]*?(?:name|property)="(?:description|og:description|twitter:description|og:title|twitter:title)"[^>]*?content="([^"]*)"[^>]*>/gi;
function stripTagsPerLine(text) {
  return text
    .split(/\r?\n/)
    .map((l) => {
      const extras = [...l.matchAll(SEMANTIC_META_RE)].map((m) => m[1]).join(" ");
      return extras ? `${l.replace(/<[^>]+>/g, " ")} ${extras}` : l.replace(/<[^>]+>/g, " ");
    })
    .join("\n");
}

export function scanPages(root = REPO_ROOT, overrides = {}) {
  // The planner (plan-manual-figures-update.mjs) probes pages with a
  // sentinel truth; the gate itself always parses the real one.
  const truth = overrides.truth ?? MANUAL_GATE.loadTruth(root);
  const allowed = overrides.allowed ?? MANUAL_GATE.allowedValueSets(truth);
  const failures = [];
  const missing = [];

  const targets = [];
  for (const l of LOCALES) {
    const rel = l === "en"
      ? join("public", "privacy-and-terms.html")
      : join("public", l, "privacy-and-terms.html");
    const abs = join(root, rel);
    if (!existsSync(abs)) {
      missing.push(rel.split(/[\\/]/).slice(-2).join("/"));
      continue;
    }
    targets.push({ abs, rel });
  }
  for (const f of [...LANDING_FILES, POCKET_FILE]) {
    const abs = join(root, "public", f);
    if (!existsSync(abs)) {
      missing.push(`public/${f}`);
      continue;
    }
    targets.push({ abs, rel: join("public", f) });
  }

  for (const { abs, rel } of targets) {
    const src = readFileSync(abs, "utf8");
    const stripped = stripTagsPerLine(compactJsonLd(src.split(/\r?\n/)))
      .split("\n")
      .map(neutralizeSpokenPrices)
      .join("\n");
    const label = rel.split(/[\\/]/).join("/");
    failures.push(...MANUAL_GATE.evaluateManual(stripped, allowed, label));
  }

  return { truth, failures, missing, scanned: targets.length };
}

export function runPageFiguresGate(root = REPO_ROOT) {
  return scanPages(root);
}

function main() {
  let result;
  try {
    result = runPageFiguresGate(process.cwd());
  } catch (error) {
    console.error(error.message);
    process.exit(2);
  }
  if (result.missing.length) {
    console.error(`[check-page-figures] FAIL: missing page(s):`);
    for (const rel of result.missing) console.error(`  - ${rel}`);
    process.exit(1);
  }
  if (result.failures.length) {
    console.error(`[check-page-figures] FAIL: ${result.failures.length} page figure drift(s):`);
    for (const f of result.failures) console.error(`  - ${f}`);
    process.exit(1);
  }
  console.log(
    `[check-page-figures] ok: ${result.scanned} pages agree with code (freeCap=${result.truth.freeMaxBookmarks}, ` +
      `devices={${result.truth.freeMaxDevices},${result.truth.proMaxDevices}}, ` +
      `prices=${result.truth.proEarlyBirdPrice}/${result.truth.proRegularPrice}, ` +
      `refund=${result.truth.refundDays}d, revalidation=${result.truth.revalidationHours}h, ` +
      `recovery=${result.truth.recoveryWords}w)`,
  );
}

const isMain =
  process.argv[1] &&
  import.meta.url === new URL(`file://${process.argv[1].replace(/\\/g, "/")}`).href;
if (isMain) {
  main();
}
