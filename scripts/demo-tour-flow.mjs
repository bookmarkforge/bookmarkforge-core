/**
 * Fixed instant used for every demo capture.
 *
 * The product renders relative timestamps (a few seconds ago) and storage
 * counters, so two captures of an identical UI taken seconds apart disagree in
 * text that has nothing to do with the interface. Pinning the clock removes that
 * noise, which is what lets the nightly drift gate use a tight pixel budget
 * instead of being muted by its own flakiness.
 *
 * `setFixedTime` is used on purpose rather than `install`: it pins Date only,
 * while timers keep running normally, so vault creation, Argon2id and the
 * scheduled UI work still complete for real during the capture.
 */
export const DEMO_FIXED_TIME = new Date('2026-09-21T12:00:00.000Z');

/** Pins the page clock. Call before the first navigation. */
export async function freezeDemoClock(page) {
  await page.clock.setFixedTime(DEMO_FIXED_TIME);
}

/** Every step logs so a hang can be located even under a killed process. */
export function step(message) {
  console.error(`[demo ${new Date().toISOString().slice(11, 19)}] ${message}`);
}

/** Hard exit so a stuck browser cannot hang the caller forever. */
export function installWatchdog(seconds) {
  const timer = setTimeout(() => {
    console.error(`[demo] watchdog: exceeded ${seconds}s, aborting`);
    process.exit(2);
  }, seconds * 1000);
  timer.unref?.();
}

/** Shared `--base-url`/`--mobile` contract for both media scripts. */
export function parseDemoArgs(argv) {
  const options = { baseUrl: "http://127.0.0.1:5173", mobile: false };
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === "--base-url") options.baseUrl = argv[++i];
    else if (argv[i] === "--mobile") options.mobile = true;
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  if (!/^https?:\/\//.test(options.baseUrl)) {
    throw new Error(`--base-url must be an absolute http(s) URL: ${options.baseUrl}`);
  }
  return options;
}

async function pauseFor(pause, ms) {
  if (typeof pause === "function") await pause(ms);
}

/**
 * The sidebar Bookmarks section is the only entry to the bookmark search.
 * No pause hook here: callers that need to linger on the list do it after this
 * resolves, once the rows are actually rendered.
 */
export async function gotoBookmarks(page) {
  await page
    .getByRole("navigation", { name: "Sidebar sections" })
    .getByRole("button", { name: "Bookmarks", exact: true })
    .click();
  await page
    .getByTestId("search-input")
    .waitFor({ state: "visible", timeout: 30_000 });
}

/** Capture one bookmark through the real QuickCapture panel. */
export async function addBookmark(page, { url, title }, { pause } = {}) {
  await page.getByTestId("add-bookmark-button").click();
  const input = page.getByTestId("quick-capture-input");
  await input.waitFor({ state: "visible" });
  await pauseFor(pause, 700);
  await input.fill(url);
  await page.getByTestId("bookmark-title-input").fill(title);
  await pauseFor(pause, 500);
  await page.getByTestId("save-bookmark-button").click();
  // onSuccess closes the capture panel — deterministic completion signal.
  await page
    .getByTestId("close-quick-capture-button")
    .waitFor({ state: "hidden", timeout: 60_000 });
}

/** Open QuickCapture and type the URL, optionally at a human pace. */
export async function fillQuickCapture(
  page,
  { url, title },
  { typeDelayMs = 0, pause } = {},
) {
  await page.getByTestId("add-bookmark-button").click();
  const input = page.getByTestId("quick-capture-input");
  await input.waitFor({ state: "visible" });
  await pauseFor(pause, 700);
  if (typeDelayMs > 0) {
    await input.pressSequentially(url, { delay: typeDelayMs });
  } else {
    await input.fill(url);
  }
  await page.getByTestId("bookmark-title-input").fill(title);
  await pauseFor(pause, 500);
}

/** Create the vault through the real UI flow (demo password only). */
export async function setupDemoVault(page, { pause, typeDelayMs = 0 } = {}) {
  await page.goto(page.url() === "about:blank" ? "/" : page.url());
  await page
    .getByRole("heading", { name: "Secure your vault" })
    .waitFor({ state: "visible", timeout: SHELL_TIMEOUT });
  await pauseFor(pause, 1100);
  await page.getByRole("button", { name: "Set up password" }).click();
  await page
    .getByRole("heading", { name: "Setup Secure Vault" })
    .waitFor({ state: "visible", timeout: SHELL_TIMEOUT });
  await pauseFor(pause, 900);

  // The recovery-kit download enables the confirmation checkbox. The kit is
  // never saved anywhere: the download object is dropped with the context.
  step("recovery kit: requesting download");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download Recovery Kit" }).click();
  await Promise.race([
    downloadPromise,
    new Promise((_, reject) =>
      setTimeout(
        () => reject(new Error("recovery kit download never started")),
        30_000,
      ),
    ),
  ]);
  step("recovery kit: download event received");
  await pauseFor(pause, 900);

  const checkbox = page.getByRole("checkbox", {
    name: "I have safely saved the recovery phrase",
  });
  await checkbox.waitFor({ state: "visible", timeout: 15_000 });
  // `check()` re-checks enabled state internally; retry briefly because the
  // enabling happens right after the download event lands.
  for (let attempt = 0; ; attempt++) {
    try {
      await checkbox.check({ timeout: 5_000 });
      break;
    } catch {
      if (attempt >= 5) throw new Error("recovery confirmation never enabled");
    }
  }
  const password = page.getByLabel("Master Password");
  if (typeDelayMs > 0) {
    await password.pressSequentially(DEMO_PASSWORD, { delay: typeDelayMs });
  } else {
    await password.fill(DEMO_PASSWORD);
  }
  await pauseFor(pause, 600);
  await page.getByRole("button", { name: "Create Vault" }).click();

  // Argon2id key derivation runs here; the recording shows the real wait.
  await page
    .getByTestId("settings-button")
    .waitFor({ state: "visible", timeout: VAULT_CRYPTO_TIMEOUT });
}

/** Dismiss onboarding wizard, tour and dashboard notices. */
export async function dismissOverlays(page) {
  for (const name of ["Skip onboarding", "Skip tour"]) {
    const button = page.getByRole("button", { name });
    if (await button.isVisible().catch(() => false)) {
      await button.click({ noWaitAfter: true }).catch(() => {});
    }
  }
  for (const name of ["Got it, remind me later", "Dismiss tip"]) {
    const button = page.getByRole("button", { name });
    if (await button.isVisible().catch(() => false)) {
      await button.evaluate((b) => b.click()).catch(() => {});
    }
  }
  for (let i = 0; i < 3; i++) {
    await page.keyboard.press("Escape").catch(() => {});
    await page.waitForTimeout(150);
    if (await page.getByTestId("settings-button").isVisible().catch(() => false)) {
      return;
    }
  }
}

/**
 * Dismiss the guided welcome tour.
 *
 * The tour is the one overlay `dismissOverlays` cannot catch reliably: it only
 * mounts ~800 ms AFTER onboarding is marked complete, so a single visibility
 * check races it and loses. It is also stored per origin (`WELCOME_TOUR_COMPLETE`),
 * so leaving it open pollutes every later page of the same demo session.
 *
 * Returns true when a tour was actually dismissed, false when none appeared
 * within `timeoutMs` (already completed, or onboarding still pending).
 */
export async function dismissWelcomeTour(page, { timeoutMs = 12_000 } = {}) {
  const skip = page.getByRole("button", { name: "Skip tour" });
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (await skip.first().isVisible().catch(() => false)) {
      await skip.first().click().catch(() => {});
      step("welcome tour dismissed");
      return true;
    }
    await page.waitForTimeout(250);
  }
  return false;
}

/**
 * The privacy consent banner (z-100) intercepts every click. Rejecting all
 * keeps the demo analytics-free, which is also the honest story for a
 * privacy-first product.
 */
export async function dismissPrivacyConsent(page) {
  const rejectAll = page.getByRole("button", { name: "Reject All" });
  if (await rejectAll.isVisible().catch(() => false)) {
    await rejectAll.click().catch(() => {});
    step("privacy consent banner dismissed");
  }
}

/** Lock through the header button and confirm inside the accessible modal. */
export async function lockDemoVault(page, { pause } = {}) {
  await page.getByRole("button", { name: "Lock Vault" }).click();
  const confirm = page
    .getByRole("dialog")
    .getByRole("button", { name: "Confirm" });
  await confirm.waitFor({ state: "visible" });
  await pauseFor(pause, 900);
  await confirm.evaluate((button) => button.click());
  await page
    .getByTestId("vault-locked-screen")
    .waitFor({ state: "visible", timeout: SHELL_TIMEOUT });
}

export async function unlockDemoVault(page, { typeDelayMs = 0, pause } = {}) {
  const password = page.getByLabel("Master Password");
  if (typeDelayMs > 0) {
    await password.pressSequentially(DEMO_PASSWORD, { delay: typeDelayMs });
  } else {
    await password.fill(DEMO_PASSWORD);
  }
  await pauseFor(pause, 400);
  await page.getByRole("button", { name: "Unlock" }).click();
  await page
    .getByTestId("settings-button")
    .waitFor({ state: "visible", timeout: VAULT_CRYPTO_TIMEOUT });
}

/** Search the bookmark list at a typing pace a viewer can follow. */
export async function searchBookmarks(page, query, { typeDelayMs = 0 } = {}) {
  const search = page.getByTestId("search-input");
  await search.click();
  if (typeDelayMs > 0) {
    await search.pressSequentially(query, { delay: typeDelayMs });
  } else {
    await search.fill(query);
  }
}
