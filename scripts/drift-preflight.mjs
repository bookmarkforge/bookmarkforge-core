#!/usr/bin/env node
/**
 * scripts/drift-preflight.mjs — pre-test warning for half-updated drift-gate
 * batches.
 *
 * Drift gates pair a regeneration script with a generated artifact:
 *
 *   scripts/audit-anchors.mjs       → scripts/audit-anchors-baseline.json
 *   scripts/doctor-docs-index.mjs   → docs/docs-state-index.md
 *   scripts/check-docs-markdown.mjs → scripts/docs-markdown-baseline.json
 *
 * When the script is newer than its artifact, the pair is probably a
 * half-updated batch — script edited, baseline pending — which is
 * indistinguishable from a real regression once the suite runs (the ADR-052
 * rollout broke the suite exactly this way on 2026-09-17; see AGENTS.md §9,
 * "Drift-gate changes move as one batch"). This check runs BEFORE the suite
 * (hooked into the bounded test runner and the fast-profile watch mode) and
 * converts that silent red into a loud, remedied warning at the top of the
 * run: it prints each stale pair, the exact `npm run gate:refresh` remedy,
 * and the escape hatch for legitimate mtime reversals (checkout, branch
 * switch, stash pop, copy — settle in a re-save or a `gate:refresh` run).
 *
 * NEVER fails by itself: a warning here is advisory; the drift gates and
 * their contract tests remain the source of truth. `--strict` inverts that
 * for callers that want mtime hygiene enforced (exits 1 on any stale pair).
 *
 * `--json` machine output for future tooling; `--strict` enforces;
 * `BMF_DRIFT_PREFLIGHT=off` disables it entirely (gate:refresh sets it,
 * because it WRITES the artifacts and would warn about itself).
 */
import { existsSync, statSync } from "node:fs";
import { join } from "node:path";

/** (gate name, script, generated baseline) — all regenerated by gate:refresh. */
export const PAIRS = [
  {
    gate: "audit-drift",
    script: "scripts/audit-anchors.mjs",
    baseline: "scripts/audit-anchors-baseline.json",
  },
  {
    gate: "docs-state-index",
    script: "scripts/doctor-docs-index.mjs",
    baseline: "docs/docs-state-index.md",
  },
  {
    gate: "docs-markdown",
    script: "scripts/check-docs-markdown.mjs",
    baseline: "scripts/docs-markdown-baseline.json",
  },
];

/**
 * Returns one entry per pair whose baseline is stale (or missing) relative
 * to its script. Deterministic: same filesystem state + same `now` clock ⇒
 * same output. `now` is injectable for tests.
 */
export function computeStalePairs(root = process.cwd(), now = Date.now()) {
  const stale = [];
  for (const pair of PAIRS) {
    const scriptPath = join(root, pair.script);
    const baselinePath = join(root, pair.baseline);
    if (!existsSync(scriptPath)) continue; // repo without this gate — skip
    if (!existsSync(baselinePath)) {
      stale.push({ ...pair, reason: "baseline missing" });
      continue;
    }
    const scriptMtime = statSync(scriptPath).mtimeMs;
    const baselineMtime = statSync(baselinePath).mtimeMs;
    if (scriptMtime > baselineMtime) {
      const deltaMin = Math.max(1, Math.round((now - baselineMtime) / 60000));
      stale.push({
        ...pair,
        reason:
          `script newer than baseline by ~${deltaMin} min ` +
          "(edited after the last regeneration?)",
      });
    }
  }
  return stale;
}

/** Human-readable multi-line report for a set of stale pairs. */
export function formatStaleReport(stale) {
  const lines = [];
  lines.push("[drift-preflight] POSSIBLY HALF-UPDATED DRIFT-GATE BATCH:");
  for (const pair of stale) {
    lines.push(`[drift-preflight]   ✗ ${pair.gate}: ${pair.script}`);
    lines.push(`[drift-preflight]       vs ${pair.baseline} — ${pair.reason}`);
  }
  lines.push(
    "[drift-preflight]   If you edited the script: run `npm run gate:refresh` " +
      "and verify its 5/5 steps BEFORE re-running tests (AGENTS.md §9).",
  );
  lines.push(
    "[drift-preflight]   If mtimes lie (checkout / branch switch / stash pop): " +
      "re-save the baseline or run `npm run gate:refresh` to settle.",
  );
  lines.push(
    "[drift-preflight]   Advisory only — the drift gates themselves decide.",
  );
  return lines.join("\n");
}

/**
 * Preflight entry point. Returns the intended exit code (0 normally —
 * warnings are advisory; 1 only under --strict with stale pairs). `out` /
 * `err` are injectable writers for tests.
 */
export function runPreflight({
  root = process.cwd(),
  argv = process.argv.slice(2),
  out = process.stdout,
  err = process.stderr,
  now = Date.now(),
} = {}) {
  if (process.env.BMF_DRIFT_PREFLIGHT === "off") return 0;

  const json = argv.includes("--json");
  const strict = argv.includes("--strict");
  const stale = computeStalePairs(root, now);

  if (json) {
    out.write(
      `${JSON.stringify({ stale: stale.length, pairs: stale }, null, 2)}\n`,
    );
  } else if (stale.length > 0) {
    err.write(`${formatStaleReport(stale)}\n\n`);
  }

  if (strict && stale.length > 0) {
    if (!json) {
      err.write("[drift-preflight] --strict: failing on stale pair(s).\n");
    }
    return 1;
  }
  return 0;
}

// Run only when invoked directly (`node scripts/drift-preflight.mjs` or via
// the npm script); importing the module (tests, hooks) must not print or exit.
const isMain =
  process.argv[1] && import.meta.url === new URL(`file://${process.argv[1].replace(/\\/g, "/")}`).href;

if (isMain) {
  process.exit(runPreflight());
}
