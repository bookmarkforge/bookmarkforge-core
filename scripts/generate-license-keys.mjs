/**
 * scripts/generate-license-keys.mjs — license signing keypair (split).
 *
 * The signing key is a SERVER-SIDE secret (see server/src/license-signing.ts).
 * The client bundle carries ONLY the
 * public verification key — never the private key. This closes the audit
 * plan 5.2.4 gap honestly: the old model shipped the (obfuscated) private
 * key in the bundle so a determined reverse-engineer could always forge
 * "Pro forever" signatures; now signing happens in a service the operator
 * controls and the app can only verify.
 *
 * Generates an RSA-PSS-2048 keypair and writes:
 *   src/services/licenseKeys.ts:
 *     - LICENSE_PUBLIC_KEY_SPKI        (base64 DER SPKI, public — committed)
 *     - LICENSE_FIXTURE_PAYLOAD        (a fixed canonical payload)
 *     - LICENSE_FIXTURE_SIGNATURE      (RSA-PSS over the fixture, signed by
 *                                       the matching private key — committed)
 *   server/.license-signing-key.pkcs8  (base64 DER PKCS#8 — GITIGNORED)
 *
 * The committed fixture lets check:license-keys (--check) and the client
 * verify tests prove that the committed public key actually verifies a
 * signature produced by its matching private key, without that private key
 * ever being committed again. The server operator loads the gitignored
 * PKCS#8 (or sets LICENSE_SIGNING_PRIVATE_KEY_PKCS8) to run the signing
 * service.
 *
 * Usage:
 *   node scripts/generate-license-keys.mjs --write   # regenerate (committed
 *                                                    # public + fixture only)
 *   node scripts/generate-license-keys.mjs --check   # CI gate: committed
 *                                                    # public key + fixture
 *                                                    # are consistent
 */
import {
  generateKeyPairSync,
  createSign,
  createVerify,
  createPrivateKey,
  createPublicKey,
  constants,
} from "node:crypto";
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const OUT_PATH = join(ROOT, "src", "services", "licenseKeys.ts");
const PRIVATE_KEY_PATH = join(ROOT, "server", ".license-signing-key.pkcs8");
const MODULUS = 2048;

/** Fixed fixture payload: stable across regenerations so the committed
 *  signature remains meaningful even if the keypair is rotated. */
const FIXTURE_PAYLOAD = {
  v: 1,
  deviceId: "fixture-device-0001",
  validatedAt: 1_700_000_000_000,
  expiresAt: 1_800_000_000_000,
  activationsLeft: 3,
  instanceId: "fixture-instance-0001",
};

/** Canonical serialization — must byte-match the client/server
 *  canonicalLicenseJson (key-sorted, undefined omitted). */
function canonicalJson(payload) {
  const sorted = {};
  for (const key of Object.keys(payload).sort()) {
    if (payload[key] !== undefined) sorted[key] = payload[key];
  }
  return JSON.stringify(sorted);
}

/** RSA-PSS (SHA-256, salt 32) sign — byte-compatible with WebCrypto. */
function signPayload(privateKeyDer, payload) {
  const signer = createSign("sha256");
  signer.update(canonicalJson(payload));
  return signer.sign({
    key: createPrivateKey({ key: privateKeyDer, format: "der", type: "pkcs8" }),
    padding: constants.RSA_PKCS1_PSS_PADDING,
    saltLength: 32,
  });
}

function verifyPayload(publicKeyDer, payload, signatureB64) {
  const verifier = createVerify("sha256");
  verifier.update(canonicalJson(payload));
  return verifier.verify(
    {
      key: createPublicKey({ key: publicKeyDer, format: "der", type: "spki" }),
      padding: constants.RSA_PKCS1_PSS_PADDING,
      saltLength: 32,
    },
    Buffer.from(signatureB64, "base64"),
  );
}

function renderModule({ publicSpki, fixtureSignature }) {
  return `// Generated by scripts/generate-license-keys.mjs — DO NOT EDIT BY HAND.
// Regenerate: node scripts/generate-license-keys.mjs --write
// Gate:       npm run check:license-keys (--check)
//
// PUBLIC VERIFICATION KEY ONLY. The matching private signing key is a
// server-side secret (see server/src/license-signing.ts). The client never
// signs — it only verifies state signed by the signing service.
//
// LICENSE_FIXTURE_PAYLOAD / LICENSE_FIXTURE_SIGNATURE are a committed
// prove-the-keypair pair: the signature is produced by the matching private
// key, so check:license-keys and the verify tests can assert that this
// public key actually validates real signatures without the private key
// being committed.
export const LICENSE_PUBLIC_KEY_SPKI =
  "${publicSpki}";
export const LICENSE_FIXTURE_SIGNATURE =
  "${fixtureSignature}";
export const LICENSE_FIXTURE_PAYLOAD = ${JSON.stringify(FIXTURE_PAYLOAD, null, 2)} as const;
`;
}

function generate() {
  const { publicKey, privateKey } = generateKeyPairSync("rsa", {
    modulusLength: MODULUS,
    publicExponent: 0x10001,
    publicKeyEncoding: { type: "spki", format: "der" },
    privateKeyEncoding: { type: "pkcs8", format: "der" },
  });
  const fixtureSignature = signPayload(privateKey, FIXTURE_PAYLOAD).toString("base64");
  return {
    publicSpki: publicKey.toString("base64"),
    privatePkcs8: privateKey.toString("base64"),
    fixtureSignature,
  };
}

/** Assert the committed module is consistent: the public key parses and the
 *  fixture signature verifies against it (sign/verify self-test). */
function checkCommitted() {
  if (!existsSync(OUT_PATH)) {
    console.error("[generate-license-keys] missing " + OUT_PATH + " — run with --write");
    process.exit(1);
  }
  const src = readFileSync(OUT_PATH, "utf8");
  const publicSpki = /LICENSE_PUBLIC_KEY_SPKI =\s*\n?\s*"([^"]+)"/.exec(src)?.[1];
  const fixtureSignature = /LICENSE_FIXTURE_SIGNATURE =\s*\n?\s*"([^"]+)"/.exec(src)?.[1];
  const fixturePayload = /LICENSE_FIXTURE_PAYLOAD = (\{[\s\S]*?\})/.exec(src)?.[1];
  if (!publicSpki || !fixtureSignature || !fixturePayload) {
    console.error("[generate-license-keys] could not parse committed keys module");
    process.exit(1);
  }
  let payload;
  try {
    payload = JSON.parse(fixturePayload);
  } catch (error) {
    console.error("[generate-license-keys] committed fixture payload is not valid JSON:", error.message);
    process.exit(1);
  }
  let publicKeyDer;
  try {
    publicKeyDer = createPublicKey({
      key: Buffer.from(publicSpki, "base64"),
      format: "der",
      type: "spki",
    }).export({ type: "spki", format: "der" });
  } catch (error) {
    console.error("[generate-license-keys] committed public key is not a valid SPKI key:", error.message);
    process.exit(1);
  }
  if (!verifyPayload(publicKeyDer, payload, fixtureSignature)) {
    console.error("[generate-license-keys] committed fixture signature does NOT verify against the committed public key — regenerate with --write");
    process.exit(1);
  }
  console.log("[generate-license-keys] committed public key OK (fixture signature verifies)");
  process.exit(0);
}

if (process.argv.includes("--check")) {
  checkCommitted();
}

const { publicSpki, privatePkcs8, fixtureSignature } = generate();
if (process.argv.includes("--write")) {
  writeFileSync(OUT_PATH, renderModule({ publicSpki, fixtureSignature }));
  mkdirSync(join(ROOT, "server"), { recursive: true });
  writeFileSync(PRIVATE_KEY_PATH, privatePkcs8 + "\n", "utf8");
  console.log(`[generate-license-keys] wrote ${OUT_PATH}`);
  console.log(`[generate-license-keys] wrote PRIVATE key to ${PRIVATE_KEY_PATH} (GITIGNORED — configure the signing service with it)`);
  console.log("[generate-license-keys] WARNING: never commit the private key; the client only needs the public key.");
  checkCommitted();
} else {
  console.log("[generate-license-keys] use --write to emit the module + private key, or --check to verify the committed one");
}
