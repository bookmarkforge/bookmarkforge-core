// Inline SVG copies of the lucide icons used by the PRE-UNLOCK screens
// (SecurityManager, SecurityConfirmation). These two screens are the FIRST
// things a user paints: the locked-vault screen and the fresh-install
// confirmation. lucide-react + motion/react both live in the 910 kB
// ui-runtime vendor chunk, so a static import here would force the browser
// to fetch + parse that whole chunk BEFORE the user can even unlock —
// the dominant remaining link in the LCP chain after the P48-P59 lazy
// boundary work. Hand-rolled SVGs keep the exact lucide geometry
// (stroke 2, round caps, 24x24 viewBox) with zero third-party weight.
// Geometry is extracted verbatim from lucide-react v1.28 icon nodes.
// Post-unlock screens may keep importing lucide normally — ui-runtime is
// already loaded for the authenticated shell.

