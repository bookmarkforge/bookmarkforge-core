import { describe, it, expect, vi, beforeEach } from "vitest";

const mockGenerateText = vi.fn();
vi.mock("../../../services/ai/ProviderManager", () => ({
  aiManager: { generateText: mockGenerateText },
}));

const mockLogger = { warn: vi.fn(), error: vi.fn(), info: vi.fn() };
vi.mock("../../../utils/logger", () => ({ logger: mockLogger }));

const { specializedAgentsService } =
  await import("../../../services/ai/SpecializedAgentsService");

describe("SpecializedAgentsService", () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  describe("executeAgent (via realidadCheck)", () => {
    it("returns text generated by aiManager", async () => {
      mockGenerateText.mockResolvedValue({ text: "analysis result" });
      const result = await specializedAgentsService.realityCheck("my idea");
      expect(result).toBe("analysis result");
    });

    it("throws if aiManager fails", async () => {
      mockGenerateText.mockRejectedValue(new Error("AI unavailable"));
      await expect(
        specializedAgentsService.realityCheck("idea"),
      ).rejects.toThrow("AI unavailable");
      expect(mockLogger.error).toHaveBeenCalled();
    });
  });

  const agentMethods = [
    ["realityCheck", "Reality Checker"],
    ["suggestTests", "QA Tester"],
    ["optimizeUI", "Frontend Wizard"],
    ["optimizeSEO", "SEO Specialist"],
    ["academicResearch", "Academic Researcher"],
    ["codeReview", "Code Reviewer"],
    ["copywriting", "Copywriter"],
    ["dataAnalysis", "Data Analyst"],
    ["uxDesign", "UX Designer"],
    ["securityAudit", "Security Auditor"],
    ["contentStrategy", "Content Strategist"],
    ["creativeDirection", "Creative Director"],
    ["architectureReview", "Architecture Reviewer"],
    ["complianceAudit", "Compliance Officer"],
    ["marketingOptimization", "Marketing Specialist"],
    ["productManagement", "Product Manager"],
    ["businessConsulting", "Business Consultant"],
    ["accessibilityAudit", "Accessibility Expert"],
    ["performanceOptimization", "Performance Optimizer"],
    ["technicalWriting", "Technical Writer"],
    ["localizationReview", "Localization Expert"],
    ["growthHacking", "Growth Hacker"],
    ["codeRefactor", "Code Refactorer"],
    ["bugHunter", "Bug Hunter"],
    ["devOpsEngineering", "DevOps Engineer"],
    ["databaseArchitecture", "Database Architect"],
    ["apiDesign", "API Designer"],
    ["cloudArchitecture", "Cloud Architect"],
    ["dataScience", "Data Scientist"],
    ["automationEngineering", "Automation Engineer"],
    ["promptEngineering", "Prompt Engineer"],
    ["brandStrategy", "Brand Strategist"],
    ["codeqlSpecialist", "CodeQL Specialist"],
    ["copilotOptimizer", "Copilot Optimizer"],
    ["legacyModernizer", "Legacy Code Modernizer"],
    ["repoManagementExpert", "Repo Management Expert"],
  ] as const;

  it.each(agentMethods)(
    "%s returns agent execution result",
    async (method) => {
      mockGenerateText.mockResolvedValue({ text: `${method} result` });
      const result = await (specializedAgentsService as any)[method](
        "input text",
      );
      expect(result).toBe(`${method} result`);
      expect(mockGenerateText).toHaveBeenCalled();
    },
  );

  it.each(agentMethods)("%s pasa isPrivate a executeAgent", async (method) => {
    mockGenerateText.mockResolvedValue({ text: "ok" });
    await (specializedAgentsService as any)[method]("input", "en", true);
    expect(mockGenerateText).toHaveBeenCalledWith(
      "input",
      expect.any(String),
      expect.objectContaining({ isPrivate: true }),
    );
  });

  describe("getNormalizedLang — branch coverage", () => {
    it("normalizes languages with region (es-MX → es)", async () => {
      mockGenerateText.mockResolvedValue({ text: "ok" });
      await specializedAgentsService.realityCheck("idea", "es-MX");
      // The built prompt contains the normalized language.
      const [, fullPrompt] = mockGenerateText.mock.calls.at(-1) as [
        string,
        string,
      ];
      expect(fullPrompt).toContain("Respond in the language: es.");
    });

    it("keeps supported languages among the 30 (fr)", async () => {
      mockGenerateText.mockResolvedValue({ text: "ok" });
      await specializedAgentsService.realityCheck("idea", "fr");
      const [, fullPrompt] = mockGenerateText.mock.calls.at(-1) as [
        string,
        string,
      ];
      // fr is one of the 30 supported locales — never falls back to en.
      expect(fullPrompt).toContain("Respond in the language: fr.");
    });

    it("falls back to 'en' when lang is an empty string", async () => {
      mockGenerateText.mockResolvedValue({ text: "ok" });
      await specializedAgentsService.realityCheck("idea", "");
      const [, fullPrompt] = mockGenerateText.mock.calls.at(-1) as [
        string,
        string,
      ];
      expect(fullPrompt).toContain("Respond in the language: en.");
    });

    it("falls back to 'en' when the language segment is empty (lang='-')", async () => {
      // "-".split("-")[0] is "" (falsy) → the `?? "en"` branch on line 7.
      mockGenerateText.mockResolvedValue({ text: "ok" });
      await specializedAgentsService.realityCheck("idea", "-");
      const [, fullPrompt] = mockGenerateText.mock.calls.at(-1) as [
        string,
        string,
      ];
      expect(fullPrompt).toContain("Respond in the language: en.");
    });

    it("falls back to 'en' when navigator is not available", async () => {
      // Cubre la rama `typeof navigator !== "undefined" ? ... : "en"`
      // simulating a browser-less environment (SSR/worker).
      vi.stubGlobal("navigator", undefined);
      try {
        mockGenerateText.mockResolvedValue({ text: "ok" });
        await specializedAgentsService.realityCheck("idea", undefined);
        const [, fullPrompt] = mockGenerateText.mock.calls.at(-1) as [
          string,
          string,
        ];
        expect(fullPrompt).toContain("Respond in the language: en.");
      } finally {
        vi.unstubAllGlobals();
      }
    });
  });

  describe("log projection (safeErrorForLog)", () => {
    it("projects executeAgent failures through the bounded shape", async () => {
      // A provider error that echoes the request prompt (with user
      // bookmark content) would leak content via logger.error today.
      // safeErrorForLog caps it to 200 chars and removes the stack.
      mockGenerateText.mockRejectedValueOnce(
        new Error(`Provider 5xx echoing prompt: ${"x".repeat(280)} ending`),
      );
      await expect(
        specializedAgentsService.realityCheck("idea"),
      ).rejects.toThrow();
      const calls = mockLogger.error.mock.calls as unknown[][];
      const failureEntry = calls.find(
        ([label, meta]: unknown[]) =>
          typeof label === "string" &&
          (label as string).includes("SpecializedAgentsService") &&
          (label as string).includes("failed"),
      );
      expect(failureEntry).toBeDefined();
      const meta = failureEntry![1] as {
        error?: { name?: unknown; message?: unknown };
      };
      expect(typeof meta.error?.name).toBe("string");
      expect(typeof meta.error?.message).toBe("string");
      expect((meta.error?.message as string).length).toBeLessThanOrEqual(220);
      expect(meta.error?.message as string).toMatch(/\u2026\[\+\d+\]/);
      expect(meta.error).not.toHaveProperty("stack");
    });
  });
});
